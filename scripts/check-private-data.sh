#!/usr/bin/env bash
# check-private-data.sh — замок против приватных данных оператора в публичном репозитории.
#
# ═══ ЗАЧЕМ ═══════════════════════════════════════════════════════════════════
# Репозиторий `sysadmin/` ПУБЛИЧНЫЙ, а знания в нём обязаны быть универсальными
# (правило C.4: запрет на хардкод инфраструктурных данных). Класс дефекта
# возвращался трижды:
#   12.06.2026 — аудит нашёл PII в публичном knowledge;
#   25.07.2026 — инвентаризация нашла следы инфраструктуры в 9 файлах;
#   04.08.2026 — в `_reference/xray-mac-chain.md` лежал ПОЛНЫЙ комплект доступа к
#                платной VPN-подписке оператора: пять узлов с адресом, портом и SNI
#                плюс клиентский UUID VLESS одной строкой.
# Трижды — значит правило не работает как правило. Нужен замок.
#
# ═══ ЧЕГО ЭТОТ ЗАМОК НЕ ДЕЛАЕТ (граница записана явно) ═══════════════════════
# 1. НЕ разбирает синтаксис: ни комментариев, ни heredoc, ни кода в кавычках.
#    Читает текст как текст, построчно. Это осознанно. Линтер переносимости
#    (ADR-0028) пал именно на парсере: нашлось ВОСЕМЬ способов одной строкой
#    выключить его целиком, потому что у него было состояние «пропускаем до …».
#    Здесь состояний нет — значит нет и способа их обмануть.
# 2. НЕ проверяет домены. В репозитории 102 разных домена, и почти все законные
#    (sing-box.sagernet.org, api.anthropic.com, xtls.github.io). Правило «домен не
#    из белого списка» превратило бы замок в паралич — а парализующий замок снимут
#    через день. Домены оператора ловятся необязательным локальным списком (ниже).
# 3. НЕ отличает упоминание от боевого значения. Цитата, пример, строка в тесте —
#    всё блокируется одинаково. Так задумано (решение оператора 25.07.2026): цена
#    лишней остановки — одна реплика, цена пропуска — утёкший доступ.
#
# ═══ ЧТО ЛОВИТ ══════════════════════════════════════════════════════════════
# R1. Публичный (маршрутизируемый) IPv4 — в содержимом И В ИМЕНИ ФАЙЛА. Приватные,
#     петлевые, служебные и общеизвестные публичные резолверы разрешены — список ниже
#     с обоснованием. Адрес, приклеенный к идентификатору (`srv_` спереди, буквы сзади),
#     тоже ловится: границы слова через \b это пропускали.
# R2. UUID — с дефисами и без (32 шестнадцатеричных знака подряд). По следам ожога
#     04.08: клиентский UUID VLESS — это ключ доступа. `gitleaks` такое НЕ ловит: он
#     знает форматы токенов известных сервисов, а UUID рядом с именем провайдера для
#     него обычная строка.
# R3. Необязательно: значения из локального списка оператора (см. LOCAL_DENYLIST).
#     Пустые строки и комментарии из списка отсеиваются — иначе замок парализован.
# R4. IPv6, полная и сжатая запись. Петля, link-local, ULA, multicast и диапазон для
#     документации 2001:db8::/32 разрешены.
#
# ═══ ЧЕГО ЗАМОК НЕ ЛОВИТ — ГРАНИЦЫ, ИЗМЕРЕННЫЕ ФИКСТУРОЙ 05.08.2026 ═════════
# Ниже — не догадки, а формы, реально прошедшие мимо при замере. Записаны, чтобы
# «✅ чисто» не читалось как «утечки невозможны»:
#  • адрес, записанный одним десятичным числом или шестнадцатеричными октетами;
#  • значение, разорванное переносом строки посередине;
#  • бинарные файлы и текст в UTF-16 (для grep это бинарь) — пропускаются целиком;
#  • домены, хостнеймы и ssh-алиасы БЕЗ локального списка R3: без файла правило молчит.
# Неразрывный пробел внутри значения раньше был в этом списке — теперь нормализуется.
#
# ═══ ОСОЗНАННЫЕ ЛОЖНЫЕ СРАБАТЫВАНИЯ ═════════════════════════════════════════
# Номер версии из четырёх и более частей, где все числа ≤255, неотличим от адреса и
# будет заблокирован. Это цена, а не дефект (правило 4 building-enforcement.md): лишняя
# остановка стоит одну реплику, пропуск — утёкший доступ. Комментарий в коде раньше
# обещал обратное — обещание было ложным и исправлено.
#
# ═══ ИСПОЛЬЗОВАНИЕ ══════════════════════════════════════════════════════════
#   scripts/check-private-data.sh                 — все отслеживаемые файлы
#   scripts/check-private-data.sh FILE [FILE...]  — только указанные
#   scripts/check-private-data.sh --staged        — версии файлов из индекса (для хука)
# Код возврата: 0 — чисто, 1 — найдено.

set -u

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || ROOT="."
cd "$ROOT" || exit 0

# ─── Разрешённые IPv4 ────────────────────────────────────────────────────────
# Точные значения. Каждое — публичная инфраструктура общего пользования либо
# общепринятый плейсхолдер, НЕ данные оператора. Добавляя строку, пиши почему.
ALLOW_EXACT_IP="
1.1.1.1|Cloudflare DNS, общеизвестный публичный резолвер
1.0.0.1|Cloudflare DNS, вторичный
8.8.8.8|Google DNS
8.8.4.4|Google DNS, вторичный
9.9.9.9|Quad9 DNS
77.88.8.8|Яндекс DNS
77.88.8.1|Яндекс DNS, вторичный
94.140.14.14|AdGuard DNS
1.2.3.4|общепринятый плейсхолдер «какой-то адрес»
160.79.104.10|диапазон Anthropic, иллюстрация «реальный IP» в объяснении socks5h
46.101.128.0|сеть DigitalOcean из открытых исследований блокировок (46.101.128.0/17)
178.63.0.0|сеть Hetzner из открытых исследований блокировок (178.63.0.0/16)
"

# Локальный список значений оператора (домены, хостнеймы, что угодно).
# Лежит ВНЕ git — иначе сам стал бы утечкой. Нет файла — правило R3 молчит.
LOCAL_DENYLIST="${PRIVATE_DATA_DENYLIST:-$ROOT/.private-denylist.local}"

# ⚠️ ПУСТАЯ СТРОКА В СПИСКЕ ПАРАЛИЗУЕТ ЗАМОК ЦЕЛИКОМ. `grep -F -f` с пустым шаблоном
# совпадает С ЛЮБОЙ строкой: один лишний перевод строки в списке — и замок начинает
# блокировать заведомо чистые файлы, после чего его снимут через день. Список ведут
# руками, так что это не гипотеза (найдено фикстурой проверщика 05.08.2026).
# Поэтому список НЕ подаётся в grep как есть: сначала выбрасываем пустые строки,
# строки из одних пробелов и комментарии `#`. Не «упрощай» обратно к -f "$LOCAL_DENYLIST".
DENYLIST_CLEAN=""
if [ -s "$LOCAL_DENYLIST" ]; then
    DENYLIST_CLEAN=$(mktemp)
    grep -v '^[[:space:]]*$' "$LOCAL_DENYLIST" 2>/dev/null \
        | grep -v '^[[:space:]]*#' > "$DENYLIST_CLEAN" 2>/dev/null || true
fi

FOUND=0

# Разрешён ли адрес: приватные/служебные диапазоны + точный список выше.
ip_allowed() {
    case "$1" in
        # Приватные (RFC1918), петля, «любой», широковещательный, link-local, CGNAT
        10.*|192.168.*|127.*|0.0.0.0|255.255.255.255|169.254.*) return 0 ;;
        172.1[6-9].*|172.2[0-9].*|172.3[01].*)                  return 0 ;;
        100.6[4-9].*|100.[7-9][0-9].*|100.1[01][0-9].*|100.12[0-7].*) return 0 ;;
        # Документационные (RFC5737) и тестовые (RFC2544) — созданы ровно для примеров
        192.0.2.*|198.51.100.*|203.0.113.*|198.1[89].*)         return 0 ;;
        # Multicast и зарезервированные
        22[4-9].*|23[0-9].*|24[0-9].*|25[0-5].*)                return 0 ;;
    esac
    # Не IPv4 по значению октетов (номер версии из четырёх частей, дата) — пропускаем.
    # Пример literal'ом здесь НЕ пишем: он сам попал бы под правило и заблокировал файл.
    local o1 o2 o3 o4
    IFS=. read -r o1 o2 o3 o4 <<EOF
$1
EOF
    for o in "$o1" "$o2" "$o3" "$o4"; do
        [ "$o" -gt 255 ] 2>/dev/null && return 0
    done
    printf '%s\n' "$ALLOW_EXACT_IP" | grep -q "^$1|" && return 0
    return 1
}

# UUID-плейсхолдеры: все нули / один и тот же символ. Остальное считаем боевым.
uuid_allowed() {
    case "$1" in
        00000000-0000-0000-0000-000000000000) return 0 ;;
        ffffffff-ffff-ffff-ffff-ffffffffffff) return 0 ;;
        FFFFFFFF-FFFF-FFFF-FFFF-FFFFFFFFFFFF) return 0 ;;
    esac
    return 1
}

report() {
    printf '  %s:%s\n' "$1" "$2"
    printf '      %s\n' "$3"
    FOUND=1
}

# ВАЖНО ПРО СКОРОСТЬ. Первая версия звала grep ДВАЖДЫ НА КАЖДУЮ СТРОКУ — прогон по
# репозиторию занимал 4 мин 38 с (343 файла). Замок, тормозящий каждый коммит на
# минуты, снимут через день, то есть медленный замок = отсутствующий замок. Чтением
# кода это не видно — видно только замером. Теперь: ОДИН grep на файл, разбор его
# вывода в шелле. Не «упрощай» обратно к grep внутри цикла по строкам.
# ГРАНИЦЫ СЛОВА НЕ ЧЕРЕЗ \b. Первая версия писала \b с обеих сторон адреса — и
# пропускала `srv_<адрес>` и `<адрес>tar`, потому что подчёркивание и буквы для \b
# «словесные». Это промах ВНУТРИ правила R1, а не за его границей: форма записи самая
# обычная, dotted-quad. Найдено фикстурой проверщика 05.08.2026. Теперь соседний символ
# обязан быть не цифрой и не точкой; лишний символ по краям снимается в scan_stream.
# Соседний символ — «не цифра». Точку в границы НЕ включаем: иначе адрес в имени файла
# (`node-<адрес>.md`) не находится, потому что за последним октетом идёт `.md`. Цена —
# пятичастная версия попадёт под правило; это осознанно, лишняя остановка дешевле утечки.
RE_IP='(^|[^0-9])([0-9]{1,3}\.){3}[0-9]{1,3}([^0-9]|$)'
RE_UUID='[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}'
# UUID без дефисов (32 hex подряд) — та же сущность, другая запись. Ограничители по краям
# нужны, чтобы не резать sha256 (64 знака) и не ловить куски длинных hex-строк.
RE_UUID32='(^|[^0-9a-fA-F])[0-9a-fA-F]{32}([^0-9a-fA-F]|$)'
# IPv6. Регулярка нарочно широкая, отсев — в scan_stream по числу двоеточий: узкая
# регулярка для IPv6 нечитаема, а широкая без отсева ловит время (12:30:45) и MAC.
# Границы обязательны: без них регулярка цепляется за КУСКИ слов вокруг двойного
# двоеточия в ключах конфигов (области видимости вида Имя::Поле::Ещё). Буквы a-f по
# краям таких ключей — валидные шестнадцатеричные цифры, поэтому обрывок ключа выглядел
# как сжатый адрес. Четыре ложных срабатывания на живом репозитории при первом прогоне.
# Примеры дословно здесь НЕ пишем: они сами попали бы под правило и заблокировали файл —
# ровно как это и случилось при первой попытке их записать.
# Соседний символ обязан быть не буквой и не цифрой; в настоящем адресе по краям стоят
# пробел, скобка, кавычка или конец строки.
RE_IPV6='(^|[^0-9a-zA-Z])([0-9a-fA-F]{0,4}:){2,7}[0-9a-fA-F]{0,4}([^0-9a-zA-Z]|$)'

# Убирает мусор по краям совпадения, оставшийся от границ (см. RE_IP).
strip_edges() {
    printf '%s' "$1" | sed -e 's/^[^0-9a-fA-F]*//' -e 's/[^0-9a-fA-F]*$//'
}

# Похоже ли на настоящий IPv6, а не на время/MAC/что-то ещё с двоеточиями.
# Порог: либо сжатая форма `::`, либо не меньше трёх двоеточий. Время `12:30:45`
# имеет два — и потому не считается адресом.
looks_like_ipv6() {
    case "$1" in
        *::*) return 0 ;;
    esac
    local colons
    colons=$(printf '%s' "$1" | tr -cd ':' | wc -c | tr -d ' ')
    [ "$colons" -ge 3 ]
}

ipv6_allowed() {
    local low
    low=$(printf '%s' "$1" | tr 'A-F' 'a-f')
    case "$low" in
        ::|::1|::1/*)              return 0 ;;  # петля
        fe80:*|fe80::*)            return 0 ;;  # link-local
        f[cd]*:*)                  return 0 ;;  # ULA fc00::/7
        ff0*:*)                    return 0 ;;  # multicast
        2001:db8:*|2001:0db8:*)    return 0 ;;  # RFC3849 — диапазон для документации
        ::ffff:*)                  return 0 ;;  # IPv4-mapped, значение проверит правило R1
    esac
    return 1
}

scan_stream() {
    local path="$1" content="$2" hits line lineno match raw

    # Неразрывный пробел и прочие «невидимые» разделители приводим к обычному пробелу
    # ДО поиска: иначе значение, разбитое таким символом, проходит молча.
    content=$(printf '%s' "$content" | sed 's/\xc2\xa0/ /g')

    # Один проход: grep -n -o отдаёт «номер_строки:совпадение» по всем правилам.
    hits=$(printf '%s\n' "$content" | grep -nEo "$RE_UUID|$RE_IPV6|$RE_IP|$RE_UUID32" 2>/dev/null)

    if [ -n "$hits" ]; then
        while IFS= read -r line; do
            [ -z "$line" ] && continue
            lineno=${line%%:*}
            raw=${line#*:}
            # РАЗБОР ЧЕРЕЗ if/elif, А НЕ ЧЕРЕЗ case — И ЭТО НЕ СТИЛЬ. В `case` ветки не
            # проваливаются: попытка поставить `*.*) : ;;` первой, чтобы «отложить»
            # IPv4, просто выключила проверку адресов целиком — 12 проверок из 20 упали
            # разом. А до этого обратный порядок (двоеточие первым) МОЛЧА пропускал
            # `<адрес>:8443`: адрес с портом вплотную уходил в ветку IPv6, не проходил
            # порог «три двоеточия» и терялся, а замок печатал «чисто». Обе поломки
            # поймал тест, не чтение. Порядок: точка → IPv4; иначе двоеточие → IPv6;
            # иначе дефис → UUID; иначе 32 hex.
            match=$(strip_edges "$raw")
            if [ "${raw#*.}" != "$raw" ]; then
                ip_allowed "$match" || report "$path" "$lineno" \
                    "публичный IP-адрес ($match) — в публичном репозитории адресов инфраструктуры быть не должно (C.4). Замени плейсхолдером или адресом из 192.0.2.0/24 (RFC5737 — для примеров). Общеизвестный публичный сервис — добавь в ALLOW_EXACT_IP с обоснованием. Номер версии из четырёх частей тоже сюда попадёт — это осознанная цена, разведи части иначе."
            elif [ "${raw#*:}" != "$raw" ]; then
                match=$(printf '%s' "$raw" | sed -e 's/^[^0-9a-fA-F:]*//' -e 's/[^0-9a-fA-F:]*$//')
                if looks_like_ipv6 "$match"; then
                    ipv6_allowed "$match" || report "$path" "$lineno" \
                        "IPv6-адрес ($match) — узлы VPN всё чаще адресуются именно так, и в публичном репозитории им не место (C.4). Для примера бери 2001:db8::/32 (RFC3849)."
                fi
            elif [ "${raw#*-}" != "$raw" ]; then
                uuid_allowed "$match" || report "$path" "$lineno" \
                    "UUID ($match) — для VLESS/Xray это КЛЮЧ ДОСТУПА, а не идентификатор. Именно так 04.08.2026 в публичный репозиторий уехал доступ к платной подписке. Убери значение; для примера годится 00000000-0000-0000-0000-000000000000."
            elif [ "${#match}" -eq 32 ]; then
                case "$match" in
                    00000000000000000000000000000000|ffffffffffffffffffffffffffffffff|FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF) ;;
                    *) report "$path" "$lineno" \
                        "32 шестнадцатеричных знака подряд ($match) — это UUID без дефисов, то есть тот же ключ доступа в другой записи. Убери значение." ;;
                esac
            fi
        done <<EOF
$hits
EOF
    fi

    # R3 — локальный список оператора (если заведён). Тоже один проход на файл.
    if [ -s "$DENYLIST_CLEAN" ]; then
        hits=$(printf '%s\n' "$content" | grep -nFf "$DENYLIST_CLEAN" 2>/dev/null)
        if [ -n "$hits" ]; then
            while IFS= read -r line; do
                [ -z "$line" ] && continue
                report "$path" "${line%%:*}" \
                    "строка содержит значение из локального списка приватных данных ($LOCAL_DENYLIST)"
            done <<EOF
$hits
EOF
        fi
    fi
}

MODE="files"
case "${1:-}" in
    --staged) MODE="staged"; shift ;;
esac

# ═══ ИМЕНА ФАЙЛОВ ЧИТАЮТСЯ ЧЕРЕЗ NUL, А НЕ ПОСТРОЧНО ═══════════════════════
# Ожог 2026-08-04, пойман первым же живым тестом хука: `git diff --cached
# --name-only` по умолчанию ЭКРАНИРУЕТ не-ASCII имена и берёт их в кавычки —
# `plan-context-engineering/01-ЭТАПЫ.md` приходит как "\320\255\320\242...".
# Такое имя не открывается, файл молча пропускается, замок печатает «чисто».
# Хук пропустил заведомо плохой коммит и отрапортовал «проверено файлов: 0».
# Лечение — `-z` (NUL-разделитель, без экранирования). Не «упрощай» обратно.
FILELIST=$(mktemp)
trap 'rm -f "$FILELIST" ${DENYLIST_CLEAN:+"$DENYLIST_CLEAN"}' EXIT

MISSING=0
if [ "$#" -gt 0 ]; then
    for f in "$@"; do
        if [ ! -e "$f" ]; then
            echo "check-private-data: нет такого файла: $f" >&2
            MISSING=1
        fi
        printf '%s\0' "$f"
    done > "$FILELIST"
elif [ "$MODE" = "staged" ]; then
    git diff --cached --name-only --diff-filter=ACMR -z > "$FILELIST"
else
    git ls-files -z > "$FILELIST"
fi

[ -s "$FILELIST" ] || { echo "✅ приватных данных не найдено (файлов для проверки нет)"; exit 0; }

CHECKED=0
SKIPPED_BINARY=0
while IFS= read -r -d '' f; do
    [ -z "$f" ] && continue
    if [ "$MODE" = "staged" ]; then
        content=$(git show ":$f" 2>/dev/null) || continue
        # Бинарные пропускаем и в этом режиме.
        #
        # НЕ через `case "$content" in *$'\000'*)`: в bash `$'\000'` — ПУСТАЯ строка
        # (NUL в переменную не помещается), шаблон вырождается в `**` и совпадает с
        # чем угодно. 04.08.2026 из-за этой строки замок объявлял бинарным КАЖДЫЙ
        # файл индекса и печатал «проверено файлов: 0» — то есть одна строка гасила
        # всю проверку. Поймано живым прогоном хука, чтением кода не видно.
        # stderr гасим у обеих сторон конвейера: grep -q выходит по первому совпадению
        # и роняет SIGPIPE в printf — это норма, но в выводе хука выглядит как ошибка.
        if ! { printf '%s' "$content" 2>/dev/null | grep -Iq . 2>/dev/null; }; then
            SKIPPED_BINARY=$((SKIPPED_BINARY + 1)); continue
        fi
    else
        [ -f "$f" ] || continue
        # Бинарные пропускаем: искать текстовые паттерны в них бессмысленно.
        # Граница задокументирована и закреплена тестом (секция [4]).
        if ! grep -Iq . "$f" 2>/dev/null; then
            SKIPPED_BINARY=$((SKIPPED_BINARY + 1)); continue
        fi
        content=$(cat "$f")
    fi
    CHECKED=$((CHECKED + 1))
    # ПУТЬ — ТОЖЕ ТЕКСТ. Файл `node-<адрес>.md` с чистым содержимым проходил молча:
    # сканировалось только содержимое. Найдено фикстурой проверщика 05.08.2026.
    scan_stream "$f (имя файла)" "$f"
    scan_stream "$f" "$content"
done < "$FILELIST"

if [ "$FOUND" -eq 1 ]; then
    echo >&2
    echo "❌ приватные данные в публичном репозитории (проверено файлов: $CHECKED)" >&2
    echo "   Удаление из файла НЕ отменяет ротацию: история публичного репозитория" >&2
    echo "   остаётся доступной. Утёк ключ — перевыпусти его у провайдера." >&2
    echo "   Осознанный обход (редко, не по привычке): git commit --no-verify" >&2
    exit 1
fi

if [ "$MISSING" -eq 1 ]; then
    echo "❌ часть указанных файлов не существует — проверка неполная (проверено: $CHECKED)" >&2
    echo "   Опечатка в аргументе не должна выглядеть как чистая проверка." >&2
    exit 1
fi

echo "✅ приватных данных не найдено (проверено файлов: $CHECKED)"
exit 0
