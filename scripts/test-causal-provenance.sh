#!/usr/bin/env bash
# test-causal-provenance.sh — тест мягкого замка ADR-0046 (scripts/check-causal-provenance.sh).
#
# Исторический дефект живёт в ПРИВАТНОМ репозитории инфры оператора (15.10.2026) — его текст в мозг не кладём (ADR-0036). Секция [1] воспроизводит его
# УСТРОЙСТВО со словами в общем виде: причинное «посчитав» без пометки источника, а через
# две строки в той же фразе — «подтвердил» про ДРУГОЕ утверждение. Именно поэтому окно ±1
# строка, а не фраза. Живой прогон по самому коммиту — в ADR-0046, «Как проверено».
#
# Запуск: bash scripts/test-causal-provenance.sh

set -u

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || ROOT="$(pwd)"
LINT="${CAUSAL_LINT:-$ROOT/scripts/check-causal-provenance.sh}"
TMP="$(mktemp -d "${TMPDIR:-/tmp}/causal-test.XXXXXX")"
PASS=0
FAIL=0

cleanup() {
    # Своя временная папка (ADR-0038): путь от mktemp, три проверки, без rm -rf.
    [ -n "${TMP:-}" ] || return 0
    case "$TMP" in */causal-test.??????) ;; *) return 0 ;; esac
    [ -d "$TMP" ] || return 0
    find "$TMP" -type f -exec rm -f {} \; 2>/dev/null
    find "$TMP" -depth -type d -exec rmdir {} \; 2>/dev/null
}
trap cleanup EXIT

ok()  { PASS=$((PASS+1)); printf '  ✅ %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  ❌ %s\n' "$1"; }

R="$TMP/repo"
mkdir -p "$R/inventory/hosts/x" "$R/incidents"
cd "$R" || exit 2
git init -q . && git config user.email t@t && git config user.name t && git config core.autocrlf false
printf 'Карточка.\n' > inventory/hosts/x/server.md
git add -A && git commit -q -m base

# Случаи: «W:текст» — обязан предупредить, «P:текст» — обязан промолчать. Между случаями —
# пустая строка, чтобы окна ±1 не пересекались. Группы без пустой строки — одно окно.
CASES=(
  # [1] устройство исторического дефекта (4 строки подряд — одно окно для средней)
  "P:проверка разрешений команды не останавливала). Первый вариант брифа не заведён: проект ждал"
  "W:сегодня второе сообщение на ≈N выше, посчитав по копии за прошлый день, а с утра точка"
  "P:сверки — на конец прошлого дня, и возвраты уже внутри неё (функция расчёта:"
  "P:точка + продажи после её дня − оплаты); проект поправку подтвердил."
  ""
  # [2] перепись форм причинных слов — каждая обязана предупредить
  "W:робот молчал, потому что очередь была пуста"
  ""
  "W:Потому что таймер стоял — проходов не было"
  ""
  "W:так как порт закрыт, сторож молчал"
  ""
  "W:т.к. сеть упала, копия не доехала"
  ""
  "W:т. к. диск полон, бэкап не прошёл"
  ""
  "W:из-за обновления ядра клиенты отвалились"
  ""
  "W:Из-за смены пути скрипт не нашёл базу"
  ""
  "W:из‑за неразрывного дефиса тоже ловится"
  ""
  "W:поскольку окно уже открыто, забор шёл заново"
  ""
  "W:по причине нехватки памяти проход оборвался"
  ""
  "W:Причина: таймер выключен руками"
  ""
  "W:Это вызвано тем, что кэш не сбросился"
  ""
  "W:решив, что сервер упал, сторож поднял тревогу"
  ""
  # [3] перепись форм пометок источника — каждая обязана промолчать
  "P:робот молчал, потому что очередь была пуста (сверено: журнал прохода)"
  ""
  "P:из-за обновления ядра клиенты отвалились — сверил по выводу версии"
  ""
  "P:потому что таймер стоял (по словам проекта, 15.10)"
  ""
  "P:так как порт закрыт — со слов коллеги"
  ""
  "P:из-за смены пути, гипотеза"
  ""
  "P:т.к. сеть упала — предположение, не проверено"
  ""
  "P:потому что кэш не сбросился, подтверждено замером"
  ""
  "P:из-за договора — проект подтвердил"
  ""
  "P:из-за правила в main.py — по коду"
  ""
  "P:потому что функция берёт первое значение — по исходнику"
  ""
  "P:из-за таймаута — по журналу службы"
  ""
  "P:потому что вывод из чтения кода такой"
  ""
  "P:из-за кэша — живьём не проверял"
  ""
  "P:из-за кэша — живьем не проверял"
  ""
  "P:потому что X — чем подтверждено: конфиг"
  ""
  "P:из-за блокировки (источник: статья, HIGH)"
  ""
  "P:причина не установлена"
  ""
  "P:причина неизвестна"
  ""
  # [4] пометка источника на соседней строке — окно ±1
  "P:робот молчал, потому что очередь была пуста —"
  "P:сверено по журналу прохода 10:02."
  ""
  # [5] омонимы и строки без причин — молчать
  "P:@sysadmin вызван агентом из сессии проекта"
  ""
  "P:у причинной цепочки обязательна строка"
  ""
  "P:проход 10:02 — код 0, ошибок нет"
)

: > inventory/hosts/x/server.md
declare -a EXP=()   # номер строки → W/P
n=0
for c in "${CASES[@]}"; do
    n=$((n+1))
    if [ -z "$c" ]; then printf '\n' >> inventory/hosts/x/server.md; EXP[$n]=""; continue; fi
    printf '%s\n' "${c#?:}" >> inventory/hosts/x/server.md
    EXP[$n]="${c%%:*}"
done
# Файл вне шаблонов путей — причины в нём молчат
printf 'робот молчал, потому что очередь была пуста\n' > README.md
git add -A

echo "[1–5] staged-режим: каждая строка-случай"
OUT="$(bash "$LINT" 2>&1)"; RC=$?
[ $RC -eq 0 ] && ok "код выхода 0 при предупреждениях (замок не блокирует)" || bad "код выхода $RC, ожидался 0"
for i in $(seq 1 "$n"); do
    e="${EXP[$i]:-}"; [ -z "$e" ] && continue
    txt="$(sed -n "${i}p" inventory/hosts/x/server.md | cut -c1-60)"
    if printf '%s\n' "$OUT" | grep -q "server.md:$i: "; then
        [ "$e" = W ] && ok "предупредил: $txt" || bad "ЛОЖНО предупредил: $txt"
    else
        [ "$e" = P ] && ok "промолчал: $txt" || bad "ПРОПУСТИЛ: $txt"
    fi
done
printf '%s\n' "$OUT" | grep -q "README.md" && bad "предупредил по файлу вне шаблонов" || ok "файл вне шаблонов (README.md) не проверялся"

echo "[6] режим --rev <коммит> даёт то же, что staged"
git commit -q -m cases
OUT2="$(bash "$LINT" --rev HEAD 2>&1)"
c1="$(printf '%s\n' "$OUT" | grep -c 'server.md:')"; c2="$(printf '%s\n' "$OUT2" | grep -c 'server.md:')"
[ "$c1" = "$c2" ] && [ "$c1" -gt 0 ] && ok "staged и --rev: по $c1 предупреждений" || bad "staged=$c1, --rev=$c2"

echo "[7] сломанный интерпретатор — замок говорит, а не молчит (правило 3д)"
OUT3="$(CAUSAL_LINT_PYTHON=/nonexistent/python bash "$LINT" --rev HEAD 2>&1)"; RC3=$?
printf '%s\n' "$OUT3" | grep -q "не выполнена" && ok "печатает «не выполнена»" || bad "молчит при сломанном python"
[ $RC3 -eq 0 ] && ok "и не блокирует коммит (код 0)" || bad "код $RC3"

echo "[8] ассерт на текст правила: канон слов не выродился (правило 3г)"
for w in 'посчитав' 'потому' 'из-за' 'по\\s+словам' 'сверено' 'гипотез'; do
    grep -q "r\"$w" "$LINT" && ok "в замке есть шаблон «${w}»" || bad "в замке нет шаблона «${w}»"
done

echo
echo "Итог: $PASS пройдено, $FAIL провалено"
[ "$FAIL" -eq 0 ]
