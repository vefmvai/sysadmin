#!/usr/bin/env bash
# check-route-targets.sh — замок против маршрута, обещающего то, чего в целевом файле нет.
#
# ═══ ЗАЧЕМ ═══════════════════════════════════════════════════════════════════
# `.claude/knowledge/*/README.md` работает маршрутизатором: строка таблицы говорит
# «вопрос или симптом → открыть такой-то файл (§раздел)». Читатель (агент) идёт по
# маршруту и НЕ проверяет, есть ли там обещанное — в этом весь смысл маршрутизатора.
# Значит, ложный маршрут стоит дороже обычной опечатки: он тратит контекст на чтение
# не того файла и создаёт уверенность, что ответа в базе нет.
#
# Класс дефекта пойман 05.08.2026 второй и третьей проверкой этапа 4Б, семь раз за три
# круга. Худший случай: строка про DNS отправляла в `routing-server-3xui.md`, где ноль
# упоминаний DNS. Маршрут был выведен из общих соображений («маршрутизация на сервере,
# значит и DNS там») и записан без сверки с файлом. Валидатор `validate-knowledge.py`
# молчал все четыре круга: он проверяет СУЩЕСТВОВАНИЕ пути, а не содержимое по ссылке.
# Правило репозитория «нарушенное дважды идёт в код» здесь выполнено с запасом.
#
# ═══ ЧТО ЛОВИТ ══════════════════════════════════════════════════════════════
# R1. Мёртвый номер раздела: маршрут ссылается на «§N», а заголовка с таким номером в
#     целевом файле нет. Диапазоны (`§9-§10`) проверяются по обоим концам.
#
# СПИСОК КАТАЛОГОВ ЖИВЁТ В ДВУХ МЕСТАХ — в регулярке целей и в отсеве строк каталога.
# Заводя новый слой (так появился `_archive/` 05.08.2026), правь ОБА: пропустишь второе —
# строка каталога нового слоя пойдёт в проверку как маршрут и даст ложное срабатывание.
# Именно это и случилось при первом же прогоне после заведения архива.
# R2. Чужой словарь: НИ ОДИН технический термин из левой колонки маршрута не встречается
#     в целевом файле. Порог намеренно слабый — «хотя бы один», см. границы.
#
# ═══ ЧЕГО ЭТОТ ЗАМОК НЕ ДЕЛАЕТ (граница записана явно) ══════════════════════
# 1. НЕ ловит смысловую инверсию. Строка «маршрут в direct, резолвинг через VPN» при
#    разделе, где написано ровно наоборот, пройдёт: слова `direct` и `VPN` в файле есть.
#    Это реальный дефект круга 3, и он остаётся за чтением человека.
# 2. НЕ ловит ОТСУТСТВУЮЩИЙ маршрут. Если тема потеряла строку — замку нечего проверять.
# 3. НЕ проверяет русские формулировки. Порог по латинским терминам и обратным кавычкам:
#    морфология русского требует стеммера, а стеммер даст ложные срабатывания, и
#    парализующий замок снимут через день (правило 4 building-enforcement.md).
# 4. Строка, где технических терминов нет вовсе, помечается как «непроверяемая» и
#    пропускается ЯВНО, с печатью в отчёт, — а не тихо. То же для строки, похожей на
#    маршрут, но с неразобранной целью: печатается предупреждение, а не молчание.
# 5. R1 (номер раздела) проверяется по ОБЪЕДИНЕНИЮ целей, а не по каждой отдельно —
#    в отличие от R2. Это осознанно: «§4.1» в строке `фaйлA §4.1 + файлB` относится к
#    одному конкретному файлу, и требовать раздел в обоих значило бы ловить ложные
#    срабатывания на каждой двухцелевой строке. Цена честная: соседняя цель способна
#    прикрыть мёртвый номер. Точная привязка «§N ↔ ближайший путь» потребовала бы
#    разбора порядка токенов в ячейке — не сделано, записано как граница.
# 6. Не различает исполнение и упоминание, как и остальные замки репозитория: «§N»
#    в тексте вопроса и строка-пример внутри блока кода будут разобраны как маршрут.
#    Это цена по правилу 4 `building-enforcement.md`, а не дефект.
#
# ═══ ИСПОЛЬЗОВАНИЕ ══════════════════════════════════════════════════════════
#   scripts/check-route-targets.sh                — все README баз знаний
#   scripts/check-route-targets.sh FILE [FILE...] — только указанные
#   scripts/check-route-targets.sh --quiet        — только проблемы
#   scripts/check-route-targets.sh --staged       — версии ИЗ ИНДЕКСА (для хука)
#
# ПОЧЕМУ --staged ОБЯЗАТЕЛЕН В ХУКЕ. Без него линтер читает рабочее дерево, и связка
# «git add плохой версии → правка файла на диске» даёт «чисто» при грязном коммите.
# Соседний замок приватных данных сделан так с самого начала; здесь этого не было, и
# независимый проверщик 05.08.2026 живьём протащил мимо хука маршрут с мёртвым §42.
# Код возврата: 0 — чисто, 1 — найдено, 2 — ошибка запуска.

set -u

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || ROOT="$(pwd)"
cd "$ROOT" || exit 2

QUIET=0
STAGED=0
FILES=()
# "$@" под `set -u` безопасно и при нуле аргументов (это особый параметр, не массив).
for arg in "$@"; do
    case "$arg" in
        --quiet) QUIET=1 ;;
        --staged) STAGED=1 ;;
        -h|--help) sed -n '2,40p' "$0"; exit 0 ;;
        *) FILES+=("$arg") ;;
    esac
done

if [ "${#FILES[@]}" -eq 0 ]; then
    while IFS= read -r f; do FILES+=("$f"); done < <(
        find .claude/knowledge -name README.md -type f 2>/dev/null | sort
    )
fi

# В staged-режиме файл может существовать только в индексе — проверка -f не годится.
if [ "$STAGED" -eq 1 ]; then
    KEEP=()
    for f in "${FILES[@]+"${FILES[@]}"}"; do
        git cat-file -e ":$f" 2>/dev/null && KEEP+=("$f")
    done
    FILES=("${KEEP[@]+"${KEEP[@]}"}")
    [ "${#FILES[@]}" -eq 0 ] && { echo "✅ маршруты: чисто (README в индексе нет)"; exit 0; }
fi

if [ "${#FILES[@]}" -eq 0 ]; then
    echo "check-route-targets: нет файлов для проверки" >&2
    exit 2
fi

# _route_target_is_private ПУТЬ — цель отсутствует «законно»: она закрыта .gitignore.
#
# Личный слой оператора (`_live/frontline-*.md`, `_live/timeline.md`) живёт только на его
# машине; в репозитории от него остаётся образец `.example`. Маршрут на такой файл верен
# для владельца и невыполним для постороннего — это разные вещи, и замок обязан их
# различать, иначе он краснеет у всех, кроме одного человека.
#
# Вне git-репозитория (распакованный архив) команда недоступна — тогда считаем цель
# обычной пропажей, то есть возвращаемся к прежнему строгому поведению.
_route_target_is_private() {
    [ -n "${1:-}" ] || return 1
    command -v git >/dev/null 2>&1 || return 1
    git check-ignore -q -- "$1" 2>/dev/null
}

FOUND=0
CHECKED_ROWS=0
SKIPPED_ROWS=0

# Термины, которые встречаются почти в каждом файле базы и потому ничего не доказывают.
# Список намеренно короткий: чем он длиннее, тем больше строк станет непроверяемыми.
is_noise_term() {
    case "$(printf '%s' "$1" | tr 'A-Z' 'a-z')" in
        vpn|md|http|https|www|ru|com|org|net|the|and|for|not|see|via) return 0 ;;
        *) return 1 ;;
    esac
}

# Есть ли в файле заголовок с указанным номером раздела.
# Принимаем формы: «## §11 …», «## 8. …», «### 2.1 …», «#### 4.1.2 …».
heading_exists() {
    local file="$1" num="$2"
    grep -qE "^#{1,6}[[:space:]]+§?${num}([.)[:space:]]|$)" "$file"
}

for src in "${FILES[@]+"${FILES[@]}"}"; do
    if [ "$STAGED" -eq 0 ] && [ ! -f "$src" ]; then
        echo "check-route-targets: нет файла $src" >&2
        FOUND=1
        continue
    fi
    src_dir="$(dirname "$src")"
    lineno=0

    if [ "$STAGED" -eq 1 ]; then
        SRC_TEXT=$(git show ":$src" 2>/dev/null) || continue
    else
        SRC_TEXT=$(cat "$src")
    fi

    while IFS= read -r line || [ -n "$line" ]; do
        lineno=$((lineno + 1))

        # Строка таблицы?
        case "$line" in
            '|'*) ;;
            *) continue ;;
        esac
        # Разделитель шапки таблицы — И ТОЛЬКО ОН. Прежняя проверка «есть три дефиса в
        # строке» выключала обе проверки для любой строки, где дефисы встретились в тексте
        # вопроса. Одна такая строка гасила замок молча (найдено проверщиком 05.08.2026).
        # Теперь: строка обязана состоять ТОЛЬКО из |, -, : и пробелов.
        case "$(printf '%s' "$line" | tr -d '|:[:space:]-')" in
            "") continue ;;
        esac

        # Первая ячейка строки. Нужна дважды: для отсева строк каталога и для R2.
        left="$(printf '%s\n' "$line" | awk -F'|' '{print $2}')"

        # Строка КАТАЛОГА, а не маршрута: путь стоит в первой ячейке («| `файл.md` | что
        # внутри |»). Каталог описывает файл, а не обещает ответ на вопрос, — проверять
        # его словарём бессмысленно и даёт ложные срабатывания (поймано живым прогоном
        # 05.08.2026 на строке про `_diagrams/`).
        # Строка КАТАЛОГА распознаётся строго: левая ячейка состоит ТОЛЬКО из пути (плюс
        # обратные кавычки и пробелы). Прежняя проверка «в левой ячейке где-то встретился
        # путь» отключала обе проверки, стоило упомянуть файл внутри текста вопроса, —
        # и делала это молча.
        left_bare="$(printf '%s' "$left" | tr -d '`[:space:]')"
        case "$left_bare" in
            _live/*.md|_reference/*.md|_meta/*.md|_diagrams/*.md|_archive/*.md|.claude/*.md) continue ;;
        esac

        # Целевые пути: только те, что указывают ВНУТРЬ базы знаний или в скилл.
        # Цели ищем в ТРЁХ записях: обратные кавычки, markdown-ссылка `](путь)` и голый
        # путь. Прежняя версия знала только первую — и любая другая запись выключала обе
        # проверки для строки, молча (проверщик 05.08.2026 протащил так пять форм).
        SLAYERS='(_live/|_reference/|_meta/|_diagrams/|_archive/|\.claude/)'
        targets=()
        while IFS= read -r p; do
            [ -n "$p" ] && targets+=("$p")
        done < <(printf '%s\n' "$line" \
            | grep -oE "\`${SLAYERS}[^\`]+\.md[^\`]*\`|\]\(${SLAYERS}[^)]+\.md[^)]*\)|${SLAYERS}[^[:space:]|)\`]+\.md" \
            | sed -e 's/^\](//' -e 's/)$//' -e 's/#.*$//' \
            | tr -d '\`' | sed -e 's/[[:space:]]*$//' | sort -u)

        if [ "${#targets[@]}" -eq 0 ]; then
            # Ни одна цель не распознана. Если в строке всё-таки упомянут .md — это не
            # «нечего проверять», а «не смог разобрать»: печатаем, а не молчим.
            # Условие узкое НАМЕРЕННО: ругаемся только если в строке есть префикс слоя,
            # то есть она выглядит как маршрут. Каталог §2 (`| имя-файла.md | описание |`)
            # префикса не имеет и сюда не попадает — иначе предупреждение печаталось бы
            # на каждой строке каталога и обесценило бы себя (поймано первым же прогоном).
            # Плюс обязательный `.md`: таблица «три слоя» называет каталоги (`_meta/`)
            # без файлов, и без этого условия ругалась бы на них.
            case "$line" in
                *.md*) : ;;
                *) continue ;;
            esac
            case "$line" in
                *_live/*|*_reference/*|*_meta/*|*_diagrams/*|*_archive/*|*.claude/*)
                    SKIPPED_ROWS=$((SKIPPED_ROWS + 1))
                    printf '  ⚠  %s:%s — строка похожа на маршрут, но цель не распознана; проверка НЕ проводилась\n' "$src" "$lineno"
                    ;;
            esac
            continue
        fi

        # Резолвим пути и оставляем существующие.
        # ВНИМАНИЕ: под bash 3.2 (штатный на macOS) при `set -u` раскрытие "${arr[@]}"
        # пустого массива — фатальная ошибка, а не пустой список. Отсюда форма
        # "${arr[@]+"${arr[@]}"}" во всех циклах ниже. Замок, падающий на первой же
        # пустой строке, замком не является.
        resolved=()
        for t in "${targets[@]+"${targets[@]}"}"; do
            if [ -f "$src_dir/$t" ]; then
                resolved+=("$src_dir/$t")
            elif [ -f "$t" ]; then
                resolved+=("$t")
            elif _route_target_is_private "$src_dir/$t" || _route_target_is_private "$t"; then
                # Файла нет, но он и НЕ ДОЛЖЕН лежать в репозитории: путь закрыт .gitignore.
                # Это личный слой оператора (например `_live/frontline-*.md` — фронт по
                # странам), в публичном репо от него остаётся только образец `.example`.
                #
                # Почему это не «маршрут в пустоту». У оператора файл есть, и маршрут ведёт
                # именно туда; у постороннего его нет и быть не может. Без этой ветки замок
                # был зелёным ровно на одной машине в мире и краснел у всех остальных,
                # блокируя ЛЮБОЙ их коммит по knowledge и скиллам (найдено 05.08.2026 на
                # чистой копии репозитория — у себя такое не увидеть в принципе).
                echo "  ℹ  $src:$lineno — цель в личном слое ($t): в репозитории её нет by design"
            else
                echo "  $src:$lineno"
                echo "      маршрут ведёт в несуществующий файл: $t"
                echo "      как чинить: поправить путь либо убрать строку — маршрут в пустоту"
                echo "      хуже отсутствия маршрута: читатель решит, что ответа в базе нет."
                FOUND=1
            fi
        done
        [ "${#resolved[@]}" -eq 0 ] && continue

        CHECKED_ROWS=$((CHECKED_ROWS + 1))

        # ── R1: номера разделов ──────────────────────────────────────────────
        sections=()
        while IFS= read -r n; do
            [ -n "$n" ] && sections+=("$n")
        done < <(printf '%s\n' "$line" | grep -oE '§[0-9]+(\.[0-9]+)*' | tr -d '§' | sort -u)

        for num in "${sections[@]+"${sections[@]}"}"; do
            hit=0
            for f in "${resolved[@]+"${resolved[@]}"}"; do
                if heading_exists "$f" "$num"; then hit=1; break; fi
            done
            if [ "$hit" -eq 0 ]; then
                echo "  $src:$lineno"
                echo "      маршрут обещает раздел §${num}, но заголовка с этим номером нет"
                echo "      ни в одном из целевых файлов: ${resolved[*]}"
                echo "      как чинить: открыть файл, найти реальный номер раздела и поправить"
                echo "      строку. Номер, взятый по памяти, — самая частая форма ложного маршрута."
                FOUND=1
            fi
        done

        # ── R2: словарь левой колонки ────────────────────────────────────────
        # Разметку снимаем ДО токенизации: иначе `**TUN**` даёт токен `TUN**`, который
        # не найдётся никогда, и замок ругается на исправную строку. Поймано живым
        # прогоном 05.08.2026 — четыре ложных срабатывания из четырёх были этим.
        left_plain="$(printf '%s\n' "$left" | tr -d '*`_')"

        anchors=()
        while IFS= read -r w; do
            [ -z "$w" ] && continue
            is_noise_term "$w" && continue
            anchors+=("$w")
        done < <(printf '%s\n' "$left_plain" \
            | grep -oE '[A-Za-z][A-Za-z0-9.-]{2,}' | sort -u)

        if [ "${#anchors[@]}" -eq 0 ]; then
            SKIPPED_ROWS=$((SKIPPED_ROWS + 1))
            [ "$QUIET" -eq 0 ] && printf '  ℹ  %s:%s — непроверяемо R2 (нет технических терминов в вопросе)\n' "$src" "$lineno"
            continue
        fi

        # ВАЖНО: проверяем КАЖДУЮ цель отдельно, а не их объединение. Первая версия
        # считала строку исправной, если термин нашёлся хоть в одном из файлов, — и
        # пропускала ровно тот дефект, ради которого замок писался: в строке про DNS
        # из коммита 761366c было две цели, вторая содержала DNS и прикрывала первую,
        # где его не было вовсе. Поймано тестом, не чтением (секция [1]).
        for f in "${resolved[@]+"${resolved[@]}"}"; do
            matched=0
            for a in "${anchors[@]+"${anchors[@]}"}"; do
                if grep -qiF -- "$a" "$f"; then matched=1; break; fi
            done
            if [ "$matched" -eq 0 ]; then
                echo "  $src:$lineno"
                echo "      НИ ОДИН термин вопроса не встречается в целевом файле."
                echo "      термины: ${anchors[*]}"
                echo "      цель:    $f"
                echo "      как чинить: маршрут почти наверняка выведен из общих соображений,"
                echo "      а не сверен с файлом. Найти поиском, где тема лежит на самом деле,"
                echo "      и переставить строку. Если темы в базе нет — сказать это прямо"
                echo "      ('нет данных'), а не отправлять читателя искать (C.2)."
                echo "      Если у строки несколько целей — проверяется КАЖДАЯ: соседняя"
                echo "      цель с нужным словом не оправдывает мёртвую."
                FOUND=1
            fi
        done
    done <<EOF
$SRC_TEXT
EOF
done

if [ "$FOUND" -eq 0 ]; then
    echo "✅ маршруты: чисто (проверено строк: $CHECKED_ROWS, из них R2 непроверяемо: $SKIPPED_ROWS)"
    exit 0
fi

echo ""
echo "🔴 маршрутизатор обещает то, чего в целевом файле нет."
echo "   Маршрут читают, не перепроверяя, — в этом его смысл и его цена."
echo "   Замок НЕ ловит смысловую инверсию и отсутствующий маршрут: это за чтением."
echo "   Осознанный обход (редко, не по привычке): git commit --no-verify"
exit 1
